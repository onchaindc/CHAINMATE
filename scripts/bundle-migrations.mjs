/**
 * Bundle every Supabase migration into one RUN_ALL.sql you can paste into the
 * Supabase SQL editor in a single go. Each migration is idempotent (safe to
 * re-run), so the bundle is too: run the whole file any number of times and
 * the database converges to the current schema.
 *
 * Usage: npm run db:bundle   (writes supabase/RUN_ALL.sql)
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "supabase", "migrations");

const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort(); // zero-padded numeric prefixes sort correctly as strings

const header = `-- ============================================================
-- ChainMate: ALL migrations in one file
-- Paste this whole file into the Supabase SQL editor and Run.
-- Safe to run more than once: every statement is idempotent,
-- so re-running never duplicates or destroys anything.
-- Generated by: npm run db:bundle  (do not edit by hand)
-- ============================================================
`;

const parts = files.map((f) => {
  const body = readFileSync(join(dir, f), "utf8").trimEnd();
  return `-- ============================================================\n-- ${f}\n-- ============================================================\n${body}\n`;
});

const out = header + parts.join("\n");
const dest = join(root, "supabase", "RUN_ALL.sql");
writeFileSync(dest, out);
console.log(`Wrote ${dest} (${files.length} migrations, ${out.split("\n").length} lines)`);
